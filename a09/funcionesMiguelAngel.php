<?php

function sumar($a, $b) {
    return $a + $b;
}

function restar($a, $b) {
    return $a - $b;
}

function multiplicar($a, $b) {
    return $a * $b;
}

function dividir($a, $b) {
    return $a / $b;
}

function calcularModulo($a, $b) {
    return $a % $b;
}

function comprobarIgualdad($a, $b) {
    return $a == $b;
}

function esPar($num) {
    return $num % 2 == 0;
}

?>